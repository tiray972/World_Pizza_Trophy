const TEXTS: Record<BookingLang, BookingTexts> = { fr, en, es, it };

export function bookingLang(lang: string | undefined): BookingLang {
  return lang === "en" || lang === "es" || lang === "it" ? lang : "fr";
}

export function bookingTexts(lang: string | undefined): BookingTexts {
  return TEXTS[bookingLang(lang)];
}

/** Remplace les {variables} d'un libellé. */
export function tf(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key) => (key in values ? String(values[key]) : match));
}
